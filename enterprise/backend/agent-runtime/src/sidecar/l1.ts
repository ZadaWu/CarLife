/**
 * 组装消息。**这是"接得住话"的地方，也是本设计最容易被改坏的地方。**
 *
 * # 为什么已说过的句子必须以 `assistant` 身份回填，而不是列进 prompt
 *
 * 头一版是把它们写成一行「刚才已经说过这些，换个角度：- xxx」，
 * 也就是当**黑名单**用。实测（2026-08-14 走查）那样出来的是三句互不相干的开场白：
 *
 * > 深圳的夏天，闷得像蒸笼，出了空调房人就化。
 * > 深圳的雨说来就来，街上的人跑得比车还快。
 * > 深圳人夏天出门，全靠一口气吊着，那热是真不讲道理。
 *
 * 三句都在讲"热"，却谁也不接谁——用户的原话是「东聊一句，西聊一句」。
 * 根因不是提示词不够狠：**"别重复"和"接着说"是两件事**，
 * 前者只约束了不许一样，没有任何东西要求后一句与前一句有关系。
 *
 * 改成把自己说过的话当成真实的对话轮次回填之后，模型面对的是
 * "我刚说了这句，现在轮到我接"，连贯性来自它自己的上文，不来自一条指令。
 *
 * # 为什么后续轮的 user 消息是一句"嗯"
 *
 * 它只是个占位——对话结构要求 user/assistant 交替。写成实质内容（比如"再说说吃的"）
 * 就成了我们在替车主指定话题，而车主此刻根本没在说话。
 */
export function guideMessages(input: {
  place?: string;
  nowText: string;
  said: readonly string[];
}): GuideMessage[] {
  const opening = [
    // 日期是给"什么当季"用的。写成光秃秃的「现在是八月」，
    // 实测它一看见就从天气起头（"这大热天的…"），而天气不在话题里。
    `现在是${input.nowText}，这个只用来想什么当季，别聊天气。`,
    input.place ? `车主话里提到的地方：${input.place}` : "车主话里没有提到任何地方。",
    "",
    "说一句。",
  ].join("\n");

  const msgs: GuideMessage[] = [{ role: "user", content: opening }];
  /*
   * 回填几句：够它**记得自己已经聊到哪儿了**。
   *
   * 试过只回填 3 句，结果是第 5 句又绕回第 1 句的话题
   * （苏州：1「小桥流水」…5「小桥流水边坐坐」）——它看不见第 1 句，
   * 于是"接着说"接的是一个已经打过转的圈。
   * 一轮最多也就六七句、每句 30 字以内，全部回填的上下文成本可以忽略。
   */
  for (const s of input.said.slice(-RECALL)) {
    msgs.push({ role: "assistant", content: s });
    msgs.push({ role: "user", content: "嗯。" });
  }
  return msgs;
}

/** 回填几句上文。见 `guideMessages` 里为什么不是 3。 */
const RECALL = 8;

/** 第 1 句的长度上限（进度前缀 23 字 + 闲话）；后续句用 `TAIL_MAX_CHARS`。 */
export const FIRST_MAX_CHARS = 60;

/**
 * 闲话本身的长度闸。
 *
 * 提示词里要的是 **25 字**，这里放到 36 —— **闸要比要求松**。
 * 卡在 30 时实测 3/30 句因 31~34 字被拒，而被拒的偏偏是展开得最好的那几句
 * （「说是早年间…」「还总有人提着竹篮叫卖自家腌的梅子」），
 * 拒了就回落成一句 L0 模板话。**为了守一个字数把最好听的一句换掉，不划算。**
 * 36 字 × 200ms/字 ≈ 7.2 秒，仍在端上等待上限（12 秒）之内。
 */
export const TAIL_MAX_CHARS = 36;

/**
 * 后置过滤。**抓得住的抓住，抓不住的靠输入限制与喂日期**（见上）。
 *
 * 返回拒绝原因；`undefined` 表示放行。拒绝即回落 L0。
 */
export function rejectGuideText(
  text: string,
  maxChars = TAIL_MAX_CHARS,
  /** 没有地名时更严：连车的事也不许沾（见 `GUIDE_SYSTEM`）。 */
  noVehicle = false,
): string | undefined {
  const t = text.trim();
  if (!t) return "空";
  if ([...t].length > maxChars) return `超长(${[...t].length}字)`;
  // 数字类：年份、距离、海拔、门票——导游最容易编的就是这些
  if (/\d/.test(t)) return "出现数字";
  /*
   * 中文数量。**先摘掉口语里的固定说法**——「一年到头」「一年四季」不是数量断言，
   * 而实测它们被这条规则误杀过（"那边一年到头绿油油的"）。
   * 误杀的代价是静默回落 L0，正好把最连贯的那一句换成一句模板话。
   */
  const bare = t.replace(/一年(到头|四季)|三三两两|三言两语|一五一十/g, "");
  if (/[一二三四五六七八九十百千万]{1,}(年|里|米|度|块|家|个世纪)/.test(bare)) return "出现数量";
  if (/(唐|宋|元|明|清|汉|民国)(代|朝)/.test(t)) return "编朝代";
  if (/(值得|一定要|推荐|建议|不妨|可以去)/.test(t)) return "推荐口气";
  if (/[？?]\s*$/.test(t)) return "反问";
  /*
   * 舞台提示与标记。实测吐出过「（顿了顿）说着说着，倒想起…」——
   * 它以为自己在写小说。这一条**必须挡在端上之前**：
   * 下游是 TTS，会一字不落地把"顿了顿"三个字念出来。
   */
  if (/[（(【\[*＊][^）)】\]*＊]*[）)】\]*＊]/.test(t)) return "带括号或标记";
  /*
   * 车的事不归它说（F-45-09 的红线：旁路不作答）。
   * 有地名时不查这条——「街上的人跑得比车还快」这种比喻是无害的；
   * 没地名时它会一路滑到"空调得开足点""最怕堵在路上"，那已经是在给用车建议了。
   */
  if (noVehicle && /(车|空调|油耗|续航|堵|路况|方向盘|导航)/.test(t)) return "绕回车上";
  return undefined;
}

/** `2026年8月`。喂给模型用。 */
export function nowText(at: number): string {
  const d = new Date(at);
  return `${d.getFullYear()}年${d.getMonth() + 1}月`;
}
