/**
 * 面向车主的那段话怎么排版——目前只有一条规则：**把关键信息标出来**。
 *
 * # 为什么规则住在这里，而不是抄进七份 prompt
 *
 * 会给车主直接读的会话有七个（`ANSWER_AGENTS` 六个 + supervisor），外加
 * `CARLIFE_ANSWER_RUNTIME=direct` 时的叙述者。同一段话抄八份的结局是**漂移**：
 * 改其中一份的人不会知道还有七份，于是"同一个助手在不同话题下排版不一样"。
 *
 * 接线点刻意与 `IDENTITY_PROMPT` 完全相同（`loadAgentPrompt` 里那一支）：
 * 判据是同一条——**这个会话的产出给谁看**。`-task` / `-intent` 的输出被代码解析
 * （`merge.ts` 的结构化字段、意图四要素 JSON），给它们塞排版规则只会往字段里
 * 掺进 `**`，而那是不会报错的那种脏数据。
 *
 * # 为什么是 `**`，不是自定义标记
 *
 * 模型本来就会写 markdown 强调，这是它最不容易写错的一种标记；而端上
 * 早就在处理它了——车机的 TTS 在念之前会把 `**` 剥掉
 * （`clients/shared/rust/carlife-tts/src/speak.rs`），所以标出来不会被念成"星星星星"。
 *
 * ⚠️ 这不违反 ADR-012。那条管的是**不要拿正则从模型文本里解析出「值」**；
 * 这里没有解析任何值，`**` 是排版信道本身，端上按它加粗，认错了最多是少一处高亮。
 */

/**
 * 关键信息标注规则。拼进人设的尾部。
 *
 * 数量上限是这段话的重点：不封顶的结果是模型把整段都加粗，
 * 而**满屏高亮等于没有高亮**——车主要扫的那一眼就又没有落点了。
 */
export const HIGHLIGHT_PROMPT = `## 关键信息要标出来

车主是在手机或车机屏幕上**扫一眼**你的回答，不是逐字读完。
所以把"他没看见就白说了"的那几个字用 \`**\` 包起来，端上会把它高亮。

标这些：订单号、车牌这类凭据；门店名与地址；日期与时间；金额；
「立刻靠边停车」这类要马上做的动作；以及让结论不作数的边界
（数据过期、只是通用说明、疑似、没查到）。

怎么标：
- **一段最多标 2 处，整条回答最多 4 处。** 标满屏等于没标。
- **只包那几个字，不包整句。** 写「订单号 \`**RB-000002**\`」，
  不要写「\`**订单号 RB-000002，门店会回拨**\`」。
- 没有这类信息就一处都不标。闲聊、反问、以及"这个我这次没查到"本身不用标。
- 除了这一种用法，回答里不要出现别的 markdown 记号（标题号、列表符号、表格、代码块）。`;
